class PersonalInfoEntity {
  final int id;
  final String name;
  final String photo;
  final String email;
  final String githubLink;
  final String cvLink;
  final String linkedinLink;
  final String whatsappNumber;

  PersonalInfoEntity({
    required this.id,
    required this.name,
    required this.photo,
    required this.email,
    required this.githubLink,
    required this.cvLink,
    required this.linkedinLink,
    required this.whatsappNumber,
  });
}
